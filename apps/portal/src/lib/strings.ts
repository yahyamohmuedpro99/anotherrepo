export type Key = keyof typeof ar;
export const STRINGS: Record<Lang, Record<Key, string>> = { ar, en };

/** Arabic-Indic digits in Arabic (matches the player), Latin digits in English. */
export function num(lang: Lang, n: number): string {
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG-u-nu-arab' : 'en').format(n);
}

export function t(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => {
    const v = params[k];
    return v === undefined ? '' : typeof v === 'number' ? num(lang, v) : v;
  });
}

/** Pick the right language from an API Localized object ({ "ar-EG": …, en: … }). */
export function pick(lang: Lang, l: Record<string, string> | undefined | null): string {
  if (!l) return '';
  return (lang === 'ar' ? (l['ar-EG'] ?? l.ar) : l.en) ?? Object.values(l)[0] ?? '';
}
