// Regenerates content/FACTCHECK.md: every fact-bearing line in every pack, with a suggested source for the reviewer.
// node tools/factcheck.mjs            → write the file
// node tools/factcheck.mjs --check    → exit 1 when the file is stale (CI)
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'content', 'FACTCHECK.md');

// Locale-key prefixes that carry claims about the real world (dialogue flavour and UI text are left out).
const FACT_PREFIXES = {
  'giza-plateau': ['sphinx', 'scarab', 'item', 'card', 'mon', 'sign', 'area'],
  'solar-system': ['fact', 'stat', 'lm', 'craft', 'card', 'quiz', 'gal', 'log', 'ast', 'item', 'body'],
};

// Suggested starting points; the reviewer confirms or replaces them and records the final source per line.
const SOURCES = [
  [/sphinx|abu ?hol|أبو الهول/i, 'https://www.britannica.com/topic/Great-Sphinx'],
  [/boat|ship|مركب/i, 'https://www.britannica.com/topic/Pyramids-of-Giza'],
  [/mercury/i, 'https://science.nasa.gov/mercury/facts/'],
  [/venus/i, 'https://science.nasa.gov/venus/venus-facts/'],
  [/\bmoon\b|lunar|apollo/i, 'https://science.nasa.gov/moon/facts/'],
  [/earth/i, 'https://science.nasa.gov/earth/facts/'],
  [/mars/i, 'https://science.nasa.gov/mars/facts/'],
  [/jupiter/i, 'https://science.nasa.gov/jupiter/jupiter-facts/'],
  [/saturn/i, 'https://science.nasa.gov/saturn/facts/'],
  [/uranus/i, 'https://science.nasa.gov/uranus/facts/'],
  [/neptune/i, 'https://science.nasa.gov/neptune/neptune-facts/'],
  [/\bsun\b|solar wind/i, 'https://science.nasa.gov/sun/facts/'],
  [/galaxy|milky way|gal\./i, 'https://science.nasa.gov/resource/the-milky-way-galaxy/'],
  [/space station|\biss\b/i, 'https://www.nasa.gov/international-space-station/'],
  [/comet/i, 'https://science.nasa.gov/solar-system/comets/'],
  [/asteroid|ast\./i, 'https://science.nasa.gov/solar-system/asteroids/'],
  [/voyager/i, 'https://science.nasa.gov/mission/voyager/'],
  [/gravity/i, 'https://science.nasa.gov/solar-system/planets/'],
];
const PACK_DEFAULT = {
  'giza-plateau': 'https://whc.unesco.org/en/list/86/',
  'solar-system': 'https://science.nasa.gov/solar-system/',
};

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = path.join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
  });
const strings = (v, out = []) => {
  if (typeof v === 'string') out.push(v);
  else if (Array.isArray(v)) v.forEach((x) => strings(x, out));
  else if (v && typeof v === 'object') Object.values(v).forEach((x) => strings(x, out));
  return out;
};
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const source = (pack, key, text) => (SOURCES.find(([re]) => re.test(key) || re.test(text)) ?? [null, PACK_DEFAULT[pack]])[1];

let md = `# Fact check register

Generated by \`node tools/factcheck.mjs\` from the packs; do not edit the tables by hand. Every line below is
content ported from the founder's prototypes and is tagged \`needs-fact-check\` until a subject expert signs it off
(BRIEF working rule 5). The source column is a **suggested starting point**, not a verification: the reviewer checks the
claim against it (or a better source), then records the outcome in the pack's review in the Studio.
The links were written without network access to those sites and have not been opened; fix any that 404.

Arabic text for each key is in \`packs/<pack>/locales/ar-EG.json\`; reviewers check both languages say the same thing.
`;

for (const pack of Object.keys(FACT_PREFIXES)) {
  const dir = path.join(ROOT, 'packs', pack);
  if (!existsSync(dir)) continue;
  const en = JSON.parse(readFileSync(path.join(dir, 'locales', 'en.json'), 'utf8'));
  const keys = new Map(); // key → where it is used
  const numbers = [];
  for (const f of walk(dir)) {
    if (f.includes(`${path.sep}locales${path.sep}`)) continue;
    const doc = JSON.parse(readFileSync(f, 'utf8'));
    if (!JSON.stringify(doc.tags ?? []).includes('needs-fact-check')) continue;
    for (const s of strings(doc)) if (en[s] !== undefined && !keys.has(s)) keys.set(s, doc.id);
    if (doc.type === 'numeric') numbers.push(doc);
  }
  for (const k of Object.keys(en)) if (FACT_PREFIXES[pack].includes(k.split('.')[0]) && !keys.has(k)) keys.set(k, '');
  const sorted = [...keys].filter(([k]) => en[k] && /\p{L}{3}/u.test(en[k])).sort(([a], [b]) => a.localeCompare(b));

  md += `\n## ${pack}\n\n${sorted.length} lines · status: **needs-fact-check**\n\n| Key | Used by | English | Suggested source |\n|---|---|---|---|\n`;
  for (const [k, by] of sorted) md += `| \`${k}\` | ${by ? `\`${by}\`` : ''} | ${cell(en[k])} | ${source(pack, k, en[k])} |\n`;
  if (numbers.length) {
    md += `\n### Numeric answers\n\n| Item | Answer | Tolerance | Suggested source |\n|---|---|---|---|\n`;
    for (const n of numbers) md += `| \`${n.id}\` | ${n.answer} | ±${n.tolerance ?? 0} | ${source(pack, n.id, en[n.prompt] ?? '')} |\n`;
  }
  md += `\nTeacher documents in \`packs/${pack}/teacher/\` repeat these facts and need the same review.\n`;
}

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== md) {
    console.error('content/FACTCHECK.md is stale: run node tools/factcheck.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, md);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
